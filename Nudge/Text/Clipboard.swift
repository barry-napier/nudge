import AppKit

/// Pastes text through the clipboard, then puts the user's clipboard back.
/// Both writes are for this Mac only, so Universal Clipboard never copies them
/// to the user's other devices. That includes putting the old clipboard back:
/// it may hold a password that was marked for this Mac only.
@MainActor
enum Clipboard {
    /// Marks our temporary clipboard content so clipboard managers skip it.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// The user's clipboard while a restore is still waiting.
    private static var pending: (saved: Snapshot, restore: Task<Void, Never>)?

    /// Returns as soon as the paste key is sent. The user's clipboard comes
    /// back a moment later, so the writer does not wait for it.
    static func paste(_ text: String) async {
        let pasteboard = NSPasteboard.general
        // A paste right after another one: the clipboard still holds our text,
        // so keep the user's clipboard from the first paste.
        let saved: Snapshot
        if let pending {
            pending.restore.cancel()
            saved = pending.saved
        } else {
            saved = snapshot(pasteboard)
        }

        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setString("", forType: transientType)
        item.setString("", forType: autoGeneratedType)
        pasteboard.writeObjects([item])
        let ourChange = pasteboard.changeCount

        KeyPoster.paste()
        // Give the app time to read the clipboard before restoring it.
        // Not cancelled by the user's Escape: only by a newer paste.
        let restoreTask = Task { @MainActor in
            await pause(milliseconds: 600)
            guard !Task.isCancelled else { return }
            pending = nil
            // Only restore if nothing else changed the clipboard meanwhile.
            if pasteboard.changeCount == ourChange {
                restore(saved, to: pasteboard)
            }
        }
        pending = (saved, restoreTask)
    }

    private typealias Snapshot = [[(NSPasteboard.PasteboardType, Data)]]

    private static func snapshot(_ pasteboard: NSPasteboard) -> Snapshot {
        (pasteboard.pasteboardItems ?? []).map { item in
            item.types.compactMap { type in item.data(forType: type).map { (type, $0) } }
        }
    }

    private static func restore(_ saved: Snapshot, to pasteboard: NSPasteboard) {
        pasteboard.prepareForNewContents(with: .currentHostOnly)
        let items = saved.map { pairs -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in pairs {
                item.setData(data, forType: type)
            }
            return item
        }
        if !items.isEmpty {
            pasteboard.writeObjects(items)
        }
    }
}

/// Waits without being cut short by task cancellation.
/// The clipboard must always be restored, even if the user cancels.
@MainActor
func pause(milliseconds: Int) async {
    await withCheckedContinuation { continuation in
        DispatchQueue.main.asyncAfter(deadline: .now() + .milliseconds(milliseconds)) {
            continuation.resume()
        }
    }
}
